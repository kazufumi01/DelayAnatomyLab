#pragma once
#include <juce_core/juce_core.h>
#include "Presets.h"
#include "Localisation.h"

// =============================================================================
//  右パネル「使い分け」と「設定のコツ」の文章（日本語／英語）
//  ・使い分け：場面 → 方式 → 目安値（理由つき）。10の場面＋隣り合う方式の違い＋「買い足す目安」
//  ・数値は、このプラグインの各方式の可動範囲（Machines.h）の中に収まる値だけを書く
// =============================================================================
inline juce::String guideText (Lang lang)
{
    const bool ja = (lang == Lang::Japanese);
    if (ja)
        return jp (
"■ まず決めること（上から順に）\n"
"1. 音の置き場所：前に出す／歌の後ろに置く／空間として溶かす\n"
"2. 暗くしたいか、粗くしたいか、揺らしたいか（＝方式の選び方）\n"
"3. Time はテンポ同期（Sync）か、ms か\n"
"4. Feedback（回数）→ HP/LP（居場所）→ Wet（量）の順に決める\n"
"迷ったら Clean で作り、最後に Machine を替えて『足りない質感』だけを足す。\n\n"

"■ 場面別の使い分け（10）\n"
"① ボーカルのメイン・エコー\n"
"   Clean／Studio Tape。1/4 か付点8分、Feedback 25%、HP 300 Hz、LP 5 kHz、Wet −14 dB、Duck 6 dB。\n"
"   理由：HP 300 でエコーが低域に被らず、LP 5k で子音のキツさが戻らず、Duck で歌詞を邪魔しない。\n"
"② ボーカルの前に出す短いエコー（スラップ）\n"
"   Studio Tape。90〜120 ms、Feedback 5%、LP 5 kHz、Wet −9 dB。\n"
"   理由：約100 ms は『別のエコー』と『同じ音』の境目。リバーブより空間を濁さず立体感が出る。\n"
"③ 厚み・ダブリング\n"
"   Clean／Pitch。Stereo で L 13 ms・R 21 ms、Mod Depth 1 ms 前後。または 28 ms ＋ Fine +14 ct。\n"
"   理由：30 ms 以内は先行音効果で『同じ音の厚み』に聴こえる。揺れが無いと不自然。Mono Check 必須。\n"
"④ ステレオに広げる\n"
"   Ping-Pong 1/8 か 1/4、HP 250 Hz。または Haas（片側 12 ms）。\n"
"   理由：左右に交互に返すと位置が動く。Haas は軽いが Mono で痩せるので Mono Check で確認。\n"
"⑤ ギター・アルペジオに奥行き\n"
"   Space Echo。350〜500 ms、Feedback 45%、LP 7 kHz。\n"
"   理由：複数ヘッドの反射が小さな群れになり、単音エコーより音が『埋まる』。\n"
"⑥ ダブ・投げ\n"
"   Echoplex。付点4分、Feedback 70%、HP 450 Hz、LP 2.5 kHz。Wet を手で動かす。\n"
"   理由：リピートごとに暗く・歪む。HP で低域の発振を防ぐ。\n"
"⑦ シンセ・パッドを後ろに置く\n"
"   BBD。150〜300 ms、Feedback 50%、Mod Depth 2〜3 ms。\n"
"   理由：Time が長いほどクロックが遅く暗くなる。暗いまま存在感が残り、揺れで古いシンセらしくなる。\n"
"⑧ エコーをリバーブのように溶かす\n"
"   Oil Can。Age 50〜90%、Feedback 60〜75%。\n"
"   理由：にじみ（Diffusion）が積み重なり、エコーの輪郭が消えて響きになる。\n"
"⑨ ローファイ・80s\n"
"   Early Digital。Age 50〜100%、Ping-Pong 1/8。\n"
"   理由：暗くならず『粗く』なる。BBD（暗い）と並べると違いが分かる。\n"
"⑩ 逆再生・ピッチ（FX）\n"
"   Reverse 400〜800 ms、Feedback 0%（歌い出し前）。Pitch +12 st In Loop（きらめき）、−12 st（沈む）。\n"
"   理由：In Loop はリピートごとに音程が積み上がり、Output は全リピートが同じ高さ。\n\n"

"■ 隣り合う方式の違い（聴き比べ：プリセット『使い分け』の A/B 1〜7）\n"
"・Clean ↔ Studio Tape：丸くなる（角が取れる）。差は小さく上品。\n"
"・Studio Tape ↔ Echoplex：暗く・歪み・揺れが増える。Time を動かすとピッチが滑る。\n"
"・Echoplex ↔ Space Echo：1本のリピートが複数の反射（タップ）の群れになる。\n"
"・Space Echo ↔ BBD：テープの暗さ（Age）から、Time と連動する暗さに変わる。\n"
"・BBD ↔ Early Digital：『暗い』と『粗い』の違い。高域は残るがザラつく。\n"
"・Early Digital ↔ Oil Can：粗さではなく『にじみ』。輪郭が溶けてリバーブに近づく。\n\n"

"■ 設定のコツ（共通）\n"
"・Feedback で回数、LP/HP で居場所、Wet で量。この3つで多くは決まる。\n"
"・テンポ同期（Sync）は曲に溶ける。付点8分は『音符が倍に聞こえる』定番、3連は跳ねる。\n"
"・歌・リードには Duck。歌っている間は引っ込み、切れ目で咲く。\n"
"・暗くしたい時は LP を下げる前に Machine と Age を試す（音色が自然に変わる）。\n"
"・Bypass と Wet Only を使い分ける：Bypass で原音との差、Wet Only でエコーだけの音色を聴く。\n"
"・Feedback 85% 以上は発振に注意。HP を上げて低域を逃がし、音量を先に下げてから触る。\n\n"

"■ 買い足す（他社プラグインを使う）目安\n"
"・Clean／Studio Tape／BBD の質感で足りる → 標準のディレイで十分。\n"
"・可動ヘッドのピッチの滑り、ヒス、プリアンプの歪みまで欲しい → テープ系の専用機（Echoplex 系）。\n"
"・リズムのタップを細かく作り込みたい → マルチタップ／マルチヘッド系。\n"
"・BBD のコーラス風の揺れや、機種ごとのフィルターを自在に動かしたい → BBD 系の専用機。\n"
"・『まず何が足りないか分からない』うちは買い足さない。A/B 1〜7 で差を言葉にできてから。\n");

    return juce::String (
"> First decide (in order)\n"
"1. Where the echo sits: forward / behind the vocal / melted into space\n"
"2. Do you want darker, rougher or swayier? (that picks the machine)\n"
"3. Tempo sync (Sync) or ms\n"
"4. Set Feedback (count), then HP/LP (position), then Wet (level)\n"
"When unsure, build with Clean and change Machine last to add only the missing character.\n\n"

"> Which one for which scene (10)\n"
"1. Main vocal echo\n"
"   Clean / Studio Tape. 1/4 or dotted 1/8, Feedback 25%, HP 300 Hz, LP 5 kHz, Wet -14 dB, Duck 6 dB.\n"
"   Why: HP 300 keeps echoes off the low end, LP 5k keeps consonants from getting harsh, Duck protects the words.\n"
"2. Short forward echo (slapback)\n"
"   Studio Tape. 90-120 ms, Feedback 5%, LP 5 kHz, Wet -9 dB.\n"
"   Why: about 100 ms is the border between 'another echo' and 'the same sound'. Adds dimension without clouding space.\n"
"3. Thickness / doubling\n"
"   Clean / Pitch. Stereo L 13 ms / R 21 ms, Mod Depth about 1 ms. Or 28 ms plus Fine +14 ct.\n"
"   Why: under 30 ms the precedence effect makes it sound like thickness. Without modulation it sounds artificial. Always check Mono.\n"
"4. Widening in stereo\n"
"   Ping-Pong 1/8 or 1/4, HP 250 Hz. Or Haas (12 ms on one side).\n"
"   Why: alternating sides moves the image. Haas is light but thins in mono, so use Mono Check.\n"
"5. Depth for guitars and arpeggios\n"
"   Space Echo. 350-500 ms, Feedback 45%, LP 7 kHz.\n"
"   Why: multi-head reflections form a small cluster that fills space better than a single echo.\n"
"6. Dub throws\n"
"   Echoplex. Dotted quarter, Feedback 70%, HP 450 Hz, LP 2.5 kHz. Ride Wet by hand.\n"
"   Why: each repeat gets darker and more distorted. HP stops low-end runaway.\n"
"7. Placing synths and pads behind\n"
"   BBD. 150-300 ms, Feedback 50%, Mod Depth 2-3 ms.\n"
"   Why: longer Time slows the clock and darkens the tone. It stays present while dark, and the sway sounds old-synth.\n"
"8. Melting echo into reverb\n"
"   Oil Can. Age 50-90%, Feedback 60-75%.\n"
"   Why: diffusion stacks, the outline vanishes, and the echo becomes ambience.\n"
"9. Lo-fi / 80s\n"
"   Early Digital. Age 50-100%, Ping-Pong 1/8.\n"
"   Why: it roughens rather than darkens. Put it next to the BBD to hear the difference.\n"
"10. Reverse and pitch (FX)\n"
"   Reverse 400-800 ms, Feedback 0% (before a vocal entrance). Pitch +12 st In Loop (shimmer), -12 st (sinking).\n"
"   Why: In Loop stacks pitch per repeat; Output keeps every repeat at the same pitch.\n\n"

"> Neighbouring machines (listen with the 'Choosing' presets A/B 1-7)\n"
"- Clean vs Studio Tape: rounder, the corners come off. Small and refined.\n"
"- Studio Tape vs Echoplex: more darkness, distortion and sway. Moving Time slides the pitch.\n"
"- Echoplex vs Space Echo: one repeat becomes a cluster of reflections (taps).\n"
"- Space Echo vs BBD: tape darkness (Age) becomes darkness tied to Time.\n"
"- BBD vs Early Digital: dark versus rough. The highs stay but it grits.\n"
"- Early Digital vs Oil Can: not grit but smear. The outline melts toward reverb.\n\n"

"> General tips\n"
"- Feedback sets the count, LP/HP the position, Wet the level. Those three decide most of it.\n"
"- Tempo sync blends into the song. Dotted 1/8 makes it sound like double the notes; triplets swing.\n"
"- Use Duck on vocals and leads: the echo steps back while singing and blooms in the gaps.\n"
"- Before lowering LP to darken, try Machine and Age (the tone changes more naturally).\n"
"- Bypass compares with the dry sound; Wet Only isolates the echo tone.\n"
"- Above Feedback 85% watch for runaway: raise HP, and lower the level first.\n\n"

"> When buying another plugin makes sense\n"
"- Clean / Studio Tape / BBD character is enough -> a stock delay is fine.\n"
"- You want moving-head pitch slides, hiss and preamp distortion -> a dedicated tape unit (Echoplex type).\n"
"- You want to design rhythmic taps in detail -> a multi-tap / multi-head delay.\n"
"- You want to move a BBD's chorus-like sway and per-machine filters freely -> a dedicated BBD unit.\n"
"- While you cannot yet say what is missing, do not buy. Describe the difference with A/B 1-7 first.\n");
}
